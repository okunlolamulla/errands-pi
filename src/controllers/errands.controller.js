import { supabase } from '../config/supabase.js';
import { ApiError, asyncHandler, dbFail } from '../utils/errors.js';
import { createErrandSchema, parseErrandId } from '../utils/validators.js';
import { logHistory } from '../services/errandService.js';
import { REQUEST_BUCKET, STATUS } from '../utils/constants.js';
import { uploadProofs } from '../services/storage.js';

// POST /api/errands  (public)  JSON, or multipart/form-data with up to 5 "photos"
export const createErrand = asyncHandler(async (req, res) => {
  const body = createErrandSchema.parse(req.body);
  // A service the admin has switched off cannot be requested.
  const { data: svc } = await supabase.from('services').select('is_active').eq('name', body.service_type).maybeSingle();
  if (svc && !svc.is_active) throw new ApiError(400, `${body.service_type} is not available right now. Please try another service or contact us.`);
  const { items, cart_id, ...rest } = body; // not columns of errand_requests
  const row = { ...rest, date_time: body.date_time ? body.date_time.toISOString() : null };

  // errand_id is generated by the database. On the rare clash (23505) just try again.
  for (let attempt = 0; attempt < 3; attempt++) {
    const { data, error } = await supabase
      .from('errand_requests').insert(row).select('errand_id, status').single();
    if (!error) {
      // Shop order: check the stock and take it off. If something ran out, undo the request and tell the customer.
      if (items?.length) {
        const { error: stockErr } = await supabase.rpc('place_order_items', { p_errand_id: data.errand_id, p_items: items });
        if (stockErr) {
          await supabase.from('errand_requests').delete().eq('errand_id', data.errand_id);
          const m = /OUT_OF_STOCK: (.+)/.exec(stockErr.message || '');
          if (m) throw new ApiError(409, `Sorry, ${m[1]} is out of stock or there is not enough left. Please update your cart.`);
          if (/UNKNOWN_PRODUCT|BAD_QUANTITY/.test(stockErr.message || '')) throw new ApiError(409, 'An item in your cart is no longer sold. Please refresh the shop and try again.');
          dbFail(stockErr);
        }
        if (cart_id) await supabase.from('carts').update({ status: 'ordered', errand_id: data.errand_id }).eq('id', cart_id);
      }
      await logHistory({ errandId: data.errand_id, from: null, to: STATUS.PENDING, note: 'Request submitted' });
      // Photos need the new errand ID for their path, so they are saved after the request itself.
      // If that fails the request still stands; the response says how many photos were kept.
      let photos_saved = 0;
      const files = req.files || [];
      if (files.length) {
        try {
          const paths = await uploadProofs(data.errand_id, files, REQUEST_BUCKET);
          await supabase.from('errand_requests').update({ request_files: paths }).eq('errand_id', data.errand_id);
          photos_saved = paths.length;
        } catch (err) { console.error('[request photos]', err); }
      }
      return res.status(201).json({ errand_id: data.errand_id, status: data.status, photos_saved });
    }
    if (error.code !== '23505') dbFail(error);
  }
  throw new ApiError(503, 'Could not create the errand. Please try again.');
});

// GET /api/errands/track/:errand_id  (public)
// The Errand ID works like a password for this page, so no name, phone, address or email is ever returned.
// While the errand is Quoted it also returns the price and payment link, so the customer can pay.
export const trackErrand = asyncHandler(async (req, res) => {
  const id = parseErrandId(req.params.errand_id);
  const { data, error } = await supabase
    .from('errand_requests')
    .select('errand_id, service_type, status, updated_at, quote_amount, quote_currency, payment_link, assigned_agent_id, approval_status, approval_note, approval_at')
    .eq('errand_id', id).maybeSingle();
  if (error) dbFail(error);
  if (!data) throw new ApiError(404, 'Errand not found');

  const out = {
    errand_id: data.errand_id, service_type: data.service_type, status: data.status, updated_at: data.updated_at,
    quote: null, payment_url: null, agent_first_name: null, closed_outcome: null,
    // Set by the admin in Errand tracking: pending | approved | disapproved (the customer site shows this as a notice).
    approval_status: data.approval_status || 'pending', approval_note: data.approval_note || null, approval_at: data.approval_at || null,
  };
  if (data.status === STATUS.QUOTED && data.quote_amount != null) {
    out.quote = { amount: data.quote_amount, currency: data.quote_currency };
    out.payment_url = data.payment_link || null;
  }
  if (data.assigned_agent_id) {
    const { data: agent } = await supabase.from('users').select('name').eq('id', data.assigned_agent_id).maybeSingle();
    out.agent_first_name = agent?.name?.split(' ')[0] || null; // first name only
  }
  if (data.status === STATUS.CLOSED) { // closed after completion, or closed early?
    const { data: done } = await supabase.from('errand_status_history').select('id')
      .eq('errand_id', id).eq('to_status', STATUS.COMPLETED).limit(1);
    out.closed_outcome = done && done.length ? 'completed' : 'cancelled';
  }
  res.json(out);
});
